export function generate({ combo, concept }) {
  const typo = combo.typography || {};
  const color = combo['color-logic'] || {};
  const layout = combo.layout || {};
  const motion = combo.motion || {};

  const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>Taste</title>
<link rel="stylesheet" href="style.css">
</head>
<body>
<main>
<h1>${escapeHtml(concept)}</h1>
<p>A distinct, opinionated design built with Taste.</p>
</main>
</body>
</html>`;

  const css = `/* Generated by Taste */
:root {
  --font-heading: ${typo.tokens?.fontHeading ?? 'sans-serif'};
  --font-body: ${typo.tokens?.fontBody ?? 'sans-serif'};
  --line-height: ${typo.tokens?.lineHeight ?? 1.5};
  --max-width: ${typo.tokens?.maxWidth ?? '70ch'};
  --bg: ${color.tokens?.background ?? '#ffffff'};
  --fg: ${color.tokens?.foreground ?? '#1a1a1a'};
  --accent: ${color.tokens?.accent ?? '#000000'};
  --transition: ${motion.tokens?.transition ?? 'none'};
}
* { box-sizing: border-box; margin: 0; padding: 0; }
html { background: var(--bg); color: var(--fg); }
body {
  font-family: var(--font-body);
  line-height: var(--line-height);
  padding: 2rem;
}
main {
  max-width: var(--max-width);
  margin: 0 auto;
}
h1 {
  font-family: var(--font-heading);
  color: var(--accent);
  transition: var(--transition);
}
p { margin-top: 1rem; color: var(--fg); }`;

  return {
    files: [
      { path: 'index.html', content: html },
      { path: 'style.css', content: css },
    ],
  };
}

function escapeHtml(s) {
  return String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}
