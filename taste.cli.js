process.on('SIGINT', () => {
  console.error('\nInterrupted. Exiting.');
  process.exit(130);
});

process.on('SIGTERM', () => {
  process.exit(143);
});

process.on('unhandledRejection', (err) => {
  console.error(`Taste error (unhandled): ${err?.message ?? err}`);
  process.exit(1);
});

async function main() {
  const argv = process.argv.slice(2);
  const { flags, positionals } = parseArgs(argv);
  const normalized = normalizeFlags(flags);
  const cwd = process.cwd();

  // Load .env (if present) before resolving config so .env vars take effect.
  loadDotEnv();

  // SEC-02: Warn when an API key is passed via command-line flags.
  if (normalized.apiKey) {
    console.error(
      'Warning: Passing API keys via --api-key exposes them to process tables and shell history. ' +
      'Use environment variables (e.g. ANTHROPIC_API_KEY) or .env files instead.'
    );
  }

  if (normalized.help === true || normalized.h === true) {
    showHelp();
    process.exit(0);
  }

  if (normalized.version === true) {
    console.log(VERSION);
    process.exit(0);
  }

  // Validate flag values (may throw TasteConfigError).
  validateFlags(normalized);

  // Configure structured logger from --verbose / TASTE_VERBOSE.
  const verbose = normalized.verbose === true || process.env.TASTE_VERBOSE === 'true' || process.env.TASTE_VERBOSE === '1';
  logger = createLogger(verbose ? 'debug' : 'warn');

  const command = positionals[0] || normalized._;

  try {
    if (command === 'init') {
      await runInit(cwd, normalized);
    } else if (command === 'critique') {
      await runCritique(cwd, normalized);
    } else if (command === 'build') {
      await runBuild(cwd, normalized);
    } else {
      showHelp();
      process.exit(1);
    }
    process.exit(0);
  } catch (err) {
    if (
      err.name === 'TasteConfigError' ||
      err.name === 'AnthropicLLMError' ||
      err.name === 'OpenAILLMError' ||
      err.name === 'FileConflictError'
    ) {
      console.error(`Taste error: ${err.message}`);
    } else {
      console.error(`Taste error: ${err.message}`);
      if (normalized.verbose === true) {
        console.error(err.stack);
      }
    }
    process.exit(1);
  }
}

main().catch((err) => {
  console.error(`Taste error: ${err.message}`);
  process.exit(1);
});
